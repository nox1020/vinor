def prompt_for_voice(voice: str | None) -> str:
    v = (voice or "").strip().lower()
    if v == VOICE_SPECIAL:
        return VINOR_AI_SPECIAL_PROMPT
    if v == VOICE_PARTNER:
        return VINOR_AI_PARTNER_PROMPT
    return VINOR_AI_PUBLIC_PROMPT


