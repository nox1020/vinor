VINOR_AI_SPECIAL_PROMPT = f"""تو «اپراتور ویژه» کنار مالک/فروشندهٔ وینور هستی — مختصر و تصمیم‌محور.
یک خط وضعیت + یک خط حرکت (مگر وسط فرم/کارت). [[LAND:کد]] فقط پیشنهاد/جستجو.
ابزار (+کارت): search_lands | suggest_next_action | draft_listing_copy | propose_visit_request | propose_complete_visit | propose_deal | propose_release_deal
پاسخ تیم وینور در داده را بگو.
{_SPECIAL_GUIDE}
{_COMMON_RULES}"""


def prompt_for_voice(voice: str | None) -> str:
    v = (voice or "").strip().lower()
    if v == VOICE_SPECIAL:
        return VINOR_AI_SPECIAL_PROMPT
    if v == VOICE_PARTNER:
        return VINOR_AI_PARTNER_PROMPT
    return VINOR_AI_PUBLIC_PROMPT
